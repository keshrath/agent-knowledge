import { describe, expect, it } from 'vitest';
import { branchName, humanText, projectName } from '../src/sessions/human.js';

describe('humanText (what a person said)', () => {
  it('a slash command is run, not asked: none, with or without its words', () => {
    expect(
      humanText(
        '<command-message>plugin-authoring</command-message>\n<command-name>/plugin-authoring</command-name>\n<command-args>do it for agent-tasks</command-args>',
      ),
    ).toBeNull();
    expect(humanText('<command-name>/clear</command-name>')).toBeNull();
    // A prompt that only starts with a slash (a path) was typed, not run.
    expect(humanText('/etc/hosts is wrong again')).toBe('/etc/hosts is wrong again');
  });

  it('drops what the host wrote: caveats, command output, reminders, notifications', () => {
    expect(
      humanText(
        '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>',
      ),
    ).toBeNull();
    expect(humanText('<local-command-stdout>Compacted</local-command-stdout>')).toBeNull();
    expect(humanText('<task-notification>agent done</task-notification>')).toBeNull();
    expect(humanText('[Request interrupted by user for tool use]')).toBeNull();
    expect(humanText('<system-reminder>be brief</system-reminder>fix the sync please')).toBe(
      'fix the sync please',
    );
  });

  it('drops a tool result or an image, keeps a plain prompt', () => {
    expect(humanText('[{"tool_use_id":"x","type":"tool_result"}]')).toBeNull();
    expect(humanText('{"type":"image","source":{"media_type":"image/png"}}')).toBeNull();
    expect(humanText('why did the git sync break')).toBe('why did the git sync break');
  });
});

describe('a project and a branch as a person names them', () => {
  it('names the project by its folder, else by the end of the store slug', () => {
    expect(projectName('C:\\Users\\me\\repos\\my-app', 'C--Users-me--repos-my-app')).toBe('my-app');
    expect(projectName('/home/me/work/api/', '-home-me-work-api')).toBe('api');
    expect(projectName('', 'C--Users-me--repos-app')).toBe('app');
  });

  it('has no branch outside git', () => {
    expect(branchName('HEAD')).toBe('');
    expect(branchName('main')).toBe('main');
  });
});
